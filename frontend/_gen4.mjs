push("    }");
push("  };");
push("");
push("  const handleConnect = async () => {");
push("    if (inputCode.trim().length === 0) {");
push('      setErrorMessage("Please enter the 4-digit code.");');
push("      return;");
push("    }");
push('    flowRef.current = "receiving";');
push("    codeRef.current = inputCode.trim();");
push("    try {");
push('      const res = await fetch("/api/join-room", {');
push('        method: "POST",');
push('        headers: { "Content-Type": "application/json" },');
push("        body: JSON.stringify({ code: inputCode.trim() }),");
push("      });");
push("      if (!res.ok) {");
push('        setErrorMessage("Code not found, please check and try again.");');
push("        return;");
push("      }");
push('      setErrorMessage("");');
push("      startPolling();");
push("      onPeerJoined();");
push("    } catch (err) {");
push('      console.error("Error joining the room", err);');
push('      setErrorMessage("Something went wrong, please try again.");');
push("    }");
push("  };");
push("");
push("  const handleSendMessage = () => {");
push("    if (dataChannelRef.current?.readyState === 'open' && messageInput.trim()) {");
push("      dataChannelRef.current.send(messageInput);");
push('      setMessageInput("");');
push("    }");
push("  };");
push("");
push("  const CHUNK_SIZE = 64 * 1024;");
push("  const BUFFER_THRESHOLD = 1 * 1024 * 1024;");
push("  const BUFFER_LOW = 512 * 1024;");
push("");
push("  const waitForDrain = (): Promise<void> =>");
push("    new Promise((resolve) => {");
push("      const channel = dataChannelRef.current;");
push("      if (!channel || channel.bufferedAmount < BUFFER_THRESHOLD) {");
push("        resolve();");
push("        return;");
push("      }");
push("      channel.bufferedAmountLowThreshold = BUFFER_LOW;");
push("      channel.addEventListener(");
push('        "bufferedamountlow",');
push("        () => resolve(),");
push("        { once: true },");
push("      );");
push("    });");
push("");
push("  const handleFileSend = async (file: File | undefined) => {");
push("    if (!file) return;");
push("    const channel = dataChannelRef.current;");
push("    if (!channel || channel.readyState !== 'open') return;");
push("    channel.send(");
push("      JSON.stringify({");
push('        type: "file-meta",');
push("        name: file.name,");
push("        size: file.size,");
push("        mime: file.type || 'application/octet-stream',");
push("      }),");
push("    );");
push("    setSendingFileName(file.name);");
push("    setSendProgress(0);");
push("    sendSpeedRef.current = { lastUpdate: 0, lastBytes: 0 };");
push('    setSendSpeedText("");');
push("    let offset = 0;");
push("    let chunksSent = 0;");
push("");
push("    const sendNextChunk = async () => {");
push("      if (offset >= file.size) {");
push("        channel.send(JSON.stringify({ type: 'file-end' }));");
push("        setSendProgress(100);");
push('        setSendSpeedText("");');
push("        transferCompletedRef.current = true;");
push("        startSelfDestruct();");
push("        return;");
push("      }");
push("      await waitForDrain();");
push("      const slice = file.slice(offset, offset + CHUNK_SIZE);");
push("      const reader = new FileReader();");
push("      reader.onload = () => {");
push("        channel.send(reader.result as ArrayBuffer);");
push("        offset += slice.size;");
push("        chunksSent++;");
push("        const now = Date.now();");
push("        if (now - sendSpeedRef.current.lastUpdate >= 1000) {");
push("          const dtSec = (now - sendSpeedRef.current.lastUpdate) / 1000;");
push("          const speed = (offset - sendSpeedRef.current.lastBytes) / dtSec;");
push("          sendSpeedRef.current.lastBytes = offset;");
push("          sendSpeedRef.current.lastUpdate = now;");
push("          setSendSpeedText(formatSpeedEta(speed, file.size - offset));");
push("        }");
push("        if (chunksSent % 10 === 0) {");
push("          setSendProgress(");
push("            Math.min(100, Math.floor((offset / file.size) * 100)),");
push("          );");
push("        }");
push("        sendNextChunk();");
push("      };");
push("      reader.readAsArrayBuffer(slice);");
push("    };");
push("    sendNextChunk();");
push("  };");
push("");
push("  const handleFileInputChange = (e: ChangeEvent<HTMLInputElement>) => {");
push("    handleFileSend(e.target.files?.[0]);");
