import { appendFileSync } from "node:fs";

const lines = [];
const push = (s) => lines.push(s);

push("");
push("  const startOffer = async () => {");
push("    const pc = setupPeerConnection();");
push('    const channel = pc.createDataChannel("file-transfer");');
push("    setupDataChannel(channel);");
push("    const offer = await pc.createOffer();");
push("    await pc.setLocalDescription(offer);");
push('    sendSignal({ type: "offer", sdp: pc.localDescription });');
push("  };");
push("");
push("  const startAnswer = () => {");
push("    const pc = setupPeerConnection();");
push("    pc.ondatachannel = (event) => {");
push("      setupDataChannel(event.channel);");
push("    };");
push("  };");
push("");
push("  const handleSignal = async (data: SignalMessage) => {");
push("    const pc = peerConnectionRef.current;");
push("    if (!pc) return;");
push("    try {");
push('      if (data.type === "offer") {');
push("        await pc.setRemoteDescription(new RTCSessionDescription(data.sdp));");
push("        const answer = await pc.createAnswer();");
push("        await pc.setLocalDescription(answer);");
push('        sendSignal({ type: "answer", sdp: pc.localDescription });');
push('      } else if (data.type === "answer") {');
push("        await pc.setRemoteDescription(new RTCSessionDescription(data.sdp));");
push('      } else if (data.type === "ice-candidate") {');
push("        try {");
push("          await pc.addIceCandidate(data.candidate);");
push("        } catch {");
push("          // Candidates can arrive out of order; ignore harmless errors");
push("        }");
push("      }");
push("    } catch (err) {");
push('      console.error("Error handling signaling message", err);');
push("    }");
push("  };");
push("");
push("  const onPeerJoined = () => {");
push("    if (peerConnectionRef.current) return;");
push('    setScreen("connected");');
push("    setStatusMessage(");
push('      flowRef.current === "receiving"');
push('        ? "Connected! (paired with sender)"');
push('        : "Connected! (peer joined)",');
push("    );");
push('    if (flowRef.current === "sending") {');
push("      startOffer();");
push("    } else {");
push("      startAnswer();");
push("    }");
push("  };");
push("");
push("  const pollOnce = async () => {");
push("    const code = codeRef.current;");
push("    if (!code) return;");
push("    try {");
push("      const res = await fetch(");
push("        `/api/signal?code=${encodeURIComponent(code)}&role=${myRole()}`");
push("      );");
push("      if (!res.ok) return;");
push("      const json = (await res.json()) as { messages?: unknown[] };");
push("      for (const raw of json.messages ?? []) {");
push("        if (!raw || typeof raw !== 'object' || !('type' in raw)) continue;");
push("        const data = raw as { type: string };");
push('        if (data.type === "peer-joined") {');
push("          onPeerJoined();");
push("        } else {");
push("          await handleSignal(raw as SignalMessage);");
push("        }");
push("      }");
push("    } catch (err) {");
push('      console.error("Error while polling for signaling messages", err);');
push("    }");
push("  };");
push("");
push("  const startPolling = () => {");
push("    stopPolling();");
push("    pollRef.current = setInterval(() => {");
push("      void pollOnce();");
push("    }, POLL_INTERVAL_MS);");
push("  };");
push("");
push("  useEffect(() => {");
push("    return () => {");
push("      stopPolling();");
push("      if (countdownRef.current !== null) {");
push("        clearInterval(countdownRef.current);");
push("        countdownRef.current = null;");
push("      }");
push("      dataChannelRef.current?.close();");
push("      peerConnectionRef.current?.close();");
push("    };");
push("  }, [stopPolling]);");

appendFileSync("app/components/WebDropTool.tsx", "\n" + lines.join("\n"));
console.log("part3 done");